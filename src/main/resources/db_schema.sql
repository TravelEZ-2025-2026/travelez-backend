CREATE TYPE user_status AS ENUM ('ACTIVE', 'BANNED');
CREATE TYPE gender_type AS ENUM ('MALE', 'FEMALE', 'OTHER');
CREATE TYPE role_type AS ENUM ('TRAVELER', 'PROVIDER', 'ADMIN');
CREATE TYPE place_status_enum AS ENUM ('OPERATIONAL', 'TEMPORARILY_CLOSED', 'PERMANENTLY_CLOSED');
CREATE TYPE media_type_enum AS ENUM ('IMAGE', 'VIDEO');
CREATE TYPE poi_type_enum AS ENUM ('ATTRACTION', 'NATURE', 'RELIGIOUS', 'NIGHTLIFE', 'SHOPPING', 'CAFE_DESSERT', 'STREET_FOOD', 'RESTAURANT', 'OTHER');
CREATE TYPE poi_status_enum AS ENUM ('ACTIVE', 'BANNED');
CREATE TYPE review_status_enum AS ENUM ('ACTIVE', 'BANNED');
CREATE TYPE auth_provider AS ENUM ('LOCAL', 'GOOGLE');

-- TABLES
CREATE TABLE users (
    id BIGSERIAL PRIMARY KEY,
    role role_type,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255),
    email VARCHAR(100) UNIQUE,
    full_name VARCHAR(100),
    gender gender_type,
    dob DATE,
    status user_status NOT NULL DEFAULT 'ACTIVE',
    avatar TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ
);
CREATE TABLE admin (
    id BIGSERIAL PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE

);
CREATE TABLE traveler (
    id BIGSERIAL PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE provider (
    id BIGSERIAL PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    phone_number VARCHAR(10) UNIQUE,
    address TEXT,
    business_name VARCHAR(100)
);

-- 2. Tạo bảng place
CREATE TABLE place (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    city_code VARCHAR(50),
    codename VARCHAR(50),
    country VARCHAR(100),
    country_code VARCHAR(10),
    region VARCHAR(100),
    latitude DECIMAL(10, 8),
    longitude DECIMAL(11, 8),
    google_place_id VARCHAR(255)
);

-- 3. Tạo bảng place_of_interest
CREATE TABLE place_of_interest (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL, --
    poi_type poi_type_enum, --
    poi_type_detail TEXT, --
    system_status poi_status_enum   DEFAULT 'ACTIVE' NOT NULL, -- 'active' or 'banned'
    address TEXT, --
    website TEXT, --
    phone_number VARCHAR(20), --
    latitude  DECIMAL(10, 8), --
    longitude DECIMAL(11, 8), --
    rating DECIMAL(3, 2), --
    review_count INT, --
    status place_status_enum NOT NULL DEFAULT 'OPERATIONAL', --
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, --
    updated_at TIMESTAMP,
    google_maps_url TEXT, -- Còn image_url (nó sẽ nằm bên media table)
    description TEXT, --
    google_place_id VARCHAR(255) UNIQUE, --
    opening_hour JSONB, --
    reviews_distribution JSONB, --
    additional_info JSONB, --
    place_id BIGINT REFERENCES place(id) ON DELETE SET NULL --
);

CREATE TABLE poi_hours (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_of_interest_id BIGINT NOT NULL REFERENCES place_of_interest(id) ON DELETE CASCADE,
    day_of_week SMALLINT NOT NULL,
    open_time TIME NOT NULL,
    close_time TIME NOT NULL,
    CONSTRAINT fk_poi_hours_poi
        FOREIGN KEY (place_of_interest_id)
        REFERENCES place_of_interest(id)
        ON DELETE CASCADE
);

CREATE TABLE review (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    google_review_id VARCHAR(255) UNIQUE, --
    status review_status_enum not null default 'ACTIVE',
    content TEXT, --
    rating DECIMAL(3, 2), --
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, --
    updated_at TIMESTAMP,
    external_name VARCHAR(255), --
    external_avt TEXT, --
    is_crawled BOOLEAN NOT NULL DEFAULT FALSE, --
    place_of_interest_id BIGINT REFERENCES place_of_interest(id) ON DELETE SET NULL,
    traveler_id BIGINT REFERENCES traveler(id) ON DELETE SET NULL
);

CREATE TABLE media (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url TEXT NOT NULL,
    type media_type_enum NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
);

CREATE TABLE media_review (
    media_id BIGINT REFERENCES media(id) ON DELETE CASCADE,
    review_id BIGINT REFERENCES review(id) ON DELETE CASCADE,
    PRIMARY KEY (media_id, review_id)
);

CREATE TABLE media_poi (
    place_of_interest_id BIGINT REFERENCES place_of_interest(id) ON DELETE CASCADE,
    media_id BIGINT REFERENCES media(id) ON DELETE CASCADE,
    PRIMARY KEY (place_of_interest_id, media_id)
);

